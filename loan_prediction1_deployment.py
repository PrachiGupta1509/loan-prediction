import streamlit as st
import pandas as pd
import numpy as np
import joblib

# Load trained regression model and saved encoders
model = joblib.load("Loan_Amount_Prediction1.pkl")
encoder = joblib.load("label_encoder1.pkl")

st.title("Loan Amount Prediction")
st.write("Enter applicant details below to estimate eligible loan amount.")

# User Input Fields (LoanAmount removed from inputs)
gender = st.selectbox("Gender", encoder["Gender"].classes_)
married = st.selectbox("Married", encoder["Married"].classes_)
dependents = st.selectbox("Dependents", encoder["Dependents"].classes_)
education = st.selectbox("Education", encoder["Education"].classes_)
self_employed = st.selectbox("Self Employed", encoder["Self_Employed"].classes_)

applicant_income = st.number_input("Applicant Income ($)", min_value=0, value=5000)
coapplicant_income = st.number_input("Coapplicant Income ($)", min_value=0, value=0)
loan_term = st.selectbox("Loan Term (Months)", [12, 36, 60, 84, 120, 180, 240, 300, 360, 480], index=8)
credit_history = st.selectbox("Credit History Clear?", [1.0, 0.0], format_func=lambda x: "Yes" if x == 1.0 else "No")
property_area = st.selectbox("Property Area", encoder["Property_Area"].classes_)
loan_status = st.selectbox("Loan Status", encoder["Loan_Status"].classes_) if "Loan_Status" in encoder else None

# Construct input DataFrame with input features only
data = {
    "Gender": [gender],
    "Married": [married],
    "Dependents": [dependents],
    "Education": [education],
    "Self_Employed": [self_employed],
    "ApplicantIncome": [applicant_income],
    "CoapplicantIncome": [coapplicant_income],
    "Loan_Amount_Term": [loan_term],
    "Property_Area": [property_area],
    "Credit_History": [credit_history]
}

if loan_status is not None:
    data["Loan_Status"] = [loan_status]

df = pd.DataFrame(data)

# Prediction logic
if st.button("Predict Loan Amount"):
    # Apply Label Encoding to categorical features
    for col in encoder:
        if col in df.columns:
            df[col] = encoder[col].transform(df[col])

    prediction = model.predict(df)

    # Display Result
    st.success(f"Estimated Eligible Loan Amount: ${prediction[0]:,.2f}")